test.skip(process.env.SILVER_V382_NATIVE!=='1','Opt-in short silver workflow.');
const silver=(w:World)=>w.piles.filter(p=>p.item==='silver');
const sum=(w:World)=>silver(w).reduce((n,p)=>n+p.quantity,0);
const merchantMoney=(w:World,id:number)=>silver(w).filter(p=>p.owner.type==='inventory'&&p.owner.pawnId===id).reduce((n,p)=>n+p.quantity,0);
const close=async(page:Page)=>{await page.keyboard.press('Escape');};
async function exportReload(page:Page,info:TestInfo,name:string){
  await pause(page);const before=await world(page);expect(validateWorld(before)).toEqual([]);
  await close(page);await panel(page,'menu');const manager=page.locator('[data-save-manager]');
  await manager.locator('[data-save-manager-name]').fill('V382 '+name);
  await manager.locator('[data-save-manager-action="create"]').click();
  await expect(manager.locator('[data-save-manager-status]')).toHaveAttribute('data-state','success');
  const download=page.waitForEvent('download');await manager.locator('[data-save-manager-action="export"]').click();
  const path=info.outputPath(name+'.json');await(await download).saveAs(path);
  expect(deserializeWorld(await decodeStoredSave(await readFile(path,'utf8')))).toEqual(before);
  await page.locator('#browse-saves').click();await page.locator('.front-menu input[type=file]').setInputFiles(path);
  await expect(page.locator('.front-menu')).toBeHidden({timeout:30_000});
  await expect(page.locator('#loading')).toHaveCount(0,{timeout:30_000});
  await pause(page);await expectWorld(page,before);await close(page);
  await info.attach(name,{path,contentType:'application/json'});return before;
}

test('V382 prepared silver wall: interruption, exact reload, physical storage and medicine purchase',async({page},info)=>{
  test.setTimeout(150_000);const errors=observeErrors(page),f=silverNativeV382(),rotation={value:0};
  const act=async(command:Command,reason:string)=>{await pause(page);await perform(page,{command,reason},rotation);await close(page);};
  const at=f.ore.z*f.initial.width+f.ore.x;
  expect(f.initial.width).toBe(32);expect(f.initial.schemaVersion).toBe(243);
  expect(ORE_DEFINITIONS.silver).toMatchObject({hp:1500,yield:40,item:'silver'});
  const merchantBefore=merchantMoney(f.initial,f.traderId),totalBefore=sum(f.initial);
  expect(silver(f.initial).filter(p=>p.owner.type==='ground')).toEqual([]);
  const path=info.outputPath('declared-preparation.json');await writeFile(path,serializeWorld(f.initial));
  await page.goto('/?e2e');const front=page.locator('.front-menu');
  await front.getByRole('button',{name:'Charger une partie',exact:true}).click();await front.locator('input[type=file]').setInputFiles(path);
  await expect(page.locator('#loading')).toHaveCount(0,{timeout:60_000});await pause(page);await expectWorld(page,f.initial);

  await revealCells(page,[f.ore]);await cell(page,f.ore.x,f.ore.z);
  await expect(page.locator('#cell-title')).toContainText('Minerai d’argent');
  await expect(page.locator('.cell-illustration')).toBeVisible();
  const icon=await page.locator('.cell-illustration').evaluate(node=>({inline:(node as HTMLElement).style.cssText,bg:getComputedStyle(node).backgroundImage,mask:getComputedStyle(node).maskImage}));
  expect(JSON.stringify(icon)).toContain('mountain-silver');
  await act({type:'area',action:'stockpile',from:f.store,to:f.store,filters:{wood:false,food:false,silver:true},items:{silver:true}},'Réserve réelle réservée à la monnaie extraite.');
  await tool(page,'mine');await revealCells(page,[f.ore]);await cell(page,f.ore.x,f.ore.z);await close(page);
  const job=(await world(page)).jobs.find(j=>j.kind==='mine'&&j.x===f.ore.x&&j.z===f.ore.z)!;expect(job).toBeDefined();
  await act({type:'order-job',pawnId:f.pawnId,jobId:job.id,queue:false},'Extraire le filon intact au vrai contact.');
  await page.locator('[data-speed="1"]').click();
  await page.waitForFunction(i=>(window.__lisiere.world.tiles[i]?.miningDamage??0)>0,at,{timeout:15_000});await pause(page);
  const contact=await world(page),miner=contact.pawns.find(p=>p.id===f.pawnId)!;
  expect(Math.max(Math.abs(miner.x-f.ore.x),Math.abs(miner.z-f.ore.z))).toBe(1);
  expect(contact.tiles[at]!.terrain).toBe('rock');expect(sum(contact)).toBe(totalBefore);
  await page.screenshot({path:info.outputPath('01-silver-contact.png')});
  await act({type:'draft',pawnIds:[f.pawnId],enabled:true},'Interrompre réellement le travail au premier coup.');
  const interrupted=await exportReload(page,info,'interrupted-rock-exact');
  expect(interrupted.pawns.find(p=>p.id===f.pawnId)!.draft).toBeTruthy();
  expect(interrupted.tiles[at]!.miningDamage).toBe(contact.tiles[at]!.miningDamage);
  expect(interrupted.tiles[at]!.miningYield).toBe(contact.tiles[at]!.miningYield);
  await act({type:'draft',pawnIds:[f.pawnId],enabled:false},'Démobiliser puis reprendre le même filon endommagé.');
  await act({type:'order-job',pawnId:f.pawnId,jobId:job.id,queue:false},'Reprendre le vrai travail, sans restaurer les dégâts.');
  await page.locator('[data-speed="6"]').click();
  await page.waitForFunction(i=>window.__lisiere.world.tiles[i]?.terrain==='rough-stone',at,{timeout:30_000});await pause(page);
  const mined=await world(page),product=mined.piles.find(p=>p.item==='silver'&&p.owner.type==='ground')!;
  expect(product).toBeDefined();expect(product.owner).toEqual({type:'ground',...f.ore});
  expect(product.quantity).toBe(ORE_DEFINITIONS.silver.yield);expect(sum(mined)).toBe(totalBefore+product.quantity);
  expect(merchantMoney(mined,f.traderId)).toBe(merchantBefore);
  await act({type:'priority',pawnId:f.pawnId,work:'haul',value:2},'Autoriser Transport après observation du produit au sol.');
  await act({type:'order-haul',pawnId:f.pawnId,target:{type:'pile',pileId:product.id},queue:false},'Transporter les seules pièces produites vers la réserve réelle.');
  await page.locator('[data-speed="1"]').click();
  await page.waitForFunction(id=>{const w=window.__lisiere.world,p=w.pawns.find(p=>p.id===id);return p?.haul?.phase==='deliver'&&p.haul.carryPileId!==null;},f.pawnId,{timeout:15_000});await pause(page);
  const carrying=await world(page),carrier=carrying.pawns.find(p=>p.id===f.pawnId)!,cargo=carrying.piles.find(p=>p.id===carrier.haul!.carryPileId)!;
  expect(carrier.haul!.sourcePileId).toBe(product.id);expect(cargo.item).toBe('silver');expect(cargo.quantity).toBe(Math.min(CARRY_CAPACITY,product.quantity));expect(carrier.haul!.quantity).toBe(cargo.quantity);
  expect(carrying.piles.find(p=>p.id===product.id)).toMatchObject({quantity:product.quantity-cargo.quantity,owner:{type:'ground',...f.ore}});
  expect(cargo.owner).toEqual({type:'pawn',pawnId:f.pawnId});expect(sum(carrying)).toBe(sum(mined));
  await page.locator('[data-speed="6"]').click();
  await page.waitForFunction(store=>{const w=window.__lisiere.world;return !w.pawns.some(p=>p.haul)&&w.piles.some(p=>p.item==='silver'&&p.owner.type==='ground'&&p.owner.x===store.x&&p.owner.z===store.z&&p.quantity===store.quantity);},{...f.store,quantity:product.quantity},{timeout:15_000});await pause(page);
  const stocked=await world(page),money=stocked.piles.find(p=>p.item==='silver'&&p.owner.type==='ground')!;
  expect(money.owner).toEqual({type:'ground',...f.store});expect(money.quantity).toBe(product.quantity);expect(sum(stocked)).toBe(sum(mined));
  await expect(page.locator('#silver')).toHaveText(String(product.quantity));
  await page.screenshot({path:info.outputPath('02-silver-stored.png')});

  await page.locator('#trade-letter').click();await page.locator('#trade-merchant').selectOption(String(f.traderId));
  await page.locator('#trade-negotiator').selectOption(String(f.pawnId));await page.locator('#trade-contact').click();
  const medicine=page.locator(`input[data-pile="${f.medicineId}"][data-side="buy"]`);
  await expect(medicine).toBeVisible({timeout:20_000});await expect(page.locator('[data-speed="0"]')).toHaveAttribute('aria-pressed','true');
  const ready=await world(page),negotiator=ready.pawns.find(p=>p.id===f.pawnId)!,trader=ready.pawns.find(p=>p.id===f.traderId)!;
  expect(negotiator.trade?.phase).toBe('ready');expect(Math.max(Math.abs(negotiator.x-trader.x),Math.abs(negotiator.z-trader.z))).toBe(1);
  // Read the live unit price actually presented, including this negotiator.
  const unitPrice=Number(await medicine.locator('xpath=ancestor::tr').locator('td').nth(3).textContent());
  expect(Number.isFinite(unitPrice)).toBe(true);
  const quote=quoteTrade(ready,f.pawnId,f.traderId,[{pileId:f.medicineId,quantity:1}]);
  if(!quote.ok)throw Error(quote.reason);
  expect(unitPrice).toBe(Number(quote.selected[0]!.good.unitPrice.toFixed(2)));const paid=quote.net;
  expect(paid).toBeGreaterThan(0);expect(paid).toBeLessThanOrEqual(product.quantity);
  await medicine.fill('1');await expect(page.locator('#trade-total')).toHaveText(`À payer : ${paid} argent.`);
  await expect(page.locator('#trade-confirm')).toBeEnabled();await page.screenshot({path:info.outputPath('03-produced-silver-basket.png')});
  const medicineBefore=ready.piles.find(p=>p.id===f.medicineId)!.quantity;
  await page.locator('#trade-confirm').click();await expect(page.locator('#trade-dialog')).not.toBeVisible();
  const bought=await world(page),receipt=bought.trade?.recent.at(-1);
  expect(receipt).toMatchObject({negotiatorId:f.pawnId,traderId:f.traderId,silver:paid,lines:[{item:'medicine',quantity:1}]});
  expect(bought.piles.find(p=>p.id===money.id)?.quantity??0).toBe(product.quantity-paid);
  expect(merchantMoney(bought,f.traderId)).toBe(merchantBefore+paid);expect(sum(bought)).toBe(totalBefore+product.quantity);
  expect(bought.piles.filter(p=>p.item==='medicine'&&p.owner.type==='ground').reduce((n,p)=>n+p.quantity,0)).toBe(1);
  expect(bought.piles.find(p=>p.id===f.medicineId)?.quantity??0).toBe(medicineBefore-1);
  const final=await exportReload(page,info,'purchased-medicine-exact');
  expect(errors).toEqual([]);expect(await page.evaluate(()=>({backend:window.__lisiere.backend,...window.__lisiere.incident})))
    .toMatchObject({backend:'WebGPU',simulationStopped:false,graphicsFault:false,waiting:0});
  await writeFile(info.outputPath('silver-native-summary.json'),JSON.stringify({notice:f.notice,schema:243,start:f.initial.tick,contact:contact.tick,interrupted:interrupted.tick,carried:carrying.tick,stored:stocked.tick,final:final.tick,ore:f.ore,store:f.store,productId:product.id,cargoId:cargo.id,firstCargoQuantity:cargo.quantity,quantity:product.quantity,medicineId:f.medicineId,unitPrice,paid,receipt,errors,scope:'One explicitly prepared32² vein and real existing merchant, no natural campaign, no performance claim.'},null,2));
});
